WITH TRIPS as (

select 
BIKEID,
USERTYPE,
BIRTH_YEAR,
DATE(TO_TIMESTAMP(STARTTIME)) AS STARTDATE,
TO_TIMESTAMP(STARTTIME) AS STARTTIME,
TO_TIMESTAMP(STOPTIME) AS STOPTIME,
TIMESTAMPDIFF(SECONDS,TO_TIMESTAMP(STARTTIME),TO_TIMESTAMP(STOPTIME)) AS TRIP_DURATION_SECONDS

from {{ source('demo', 'bike') }}

)

select * from TRIPS